// Builds supabase/functions/site-assistant/knowledge.ts from the website's own data files, so the
// assistant always describes the same products the site shows. Run:  npm run build:assistant
// Deliberately EXCLUDED: protected documentation and any payment/bank details.
import { build } from 'esbuild';
import { writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const dir = mkdtempSync(join(tmpdir(), 'kb-'));
const entry = join(dir, 'entry.ts');
const out = join(dir, 'out.mjs');
writeFileSync(entry, `
export { site, coreAreas, whyChoose, industries } from '${process.cwd()}/src/data/site.ts';
export { products } from '${process.cwd()}/src/data/products.ts';
export { catalog } from '${process.cwd()}/src/data/catalog.ts';
`);
await build({ entryPoints: [entry], bundle: true, format: 'esm', platform: 'node', outfile: out, loader: { '.png': 'dataurl', '.jpg': 'dataurl' }, logLevel: 'error' });
const { site, coreAreas, whyChoose, industries, products, catalog } = await import(pathToFileURL(out).href);
rmSync(dir, { recursive: true, force: true });

const L = [];
L.push(`# ${site.name} — website knowledge`);
L.push(`Motto: ${site.motto}`);
L.push(`Contact: email ${site.email}, phone/WhatsApp ${site.phone}. Energy Management Dashboard: ${site.dashboardUrl}`);
L.push(`Core areas: ${coreAreas.join('; ')}.`);
L.push(`Industries served: ${industries.map((i) => i.label).join('; ')}.`);
L.push('\n## Why choose MOTECH');
for (const w of whyChoose) L.push(`- ${w.title}: ${w.body}`);
L.push('\n## Flagship solutions (home page, "Products")');
for (const p of products) {
  L.push(`\n### ${p.name} — ${p.tagline}`);
  L.push(p.description);
  L.push(`Features: ${p.features.join('; ')}.`);
  L.push(`Applications: ${p.applications.join('; ')}.`);
  if (p.benefits?.length) L.push(`Benefits: ${p.benefits.join('; ')}.`);
}
L.push('\n## Online store hardware (path /store/<slug>) — prices are NOT listed here; use the get_catalog tool for live prices');
for (const c of catalog) {
  L.push(`\n### ${c.name} (slug: ${c.slug}, category: ${c.category})`);
  L.push(c.summary);
  L.push(c.description);
  if (c.features?.length) L.push(`Features: ${c.features.join('; ')}.`);
  if (c.applications?.length) L.push(`Applications: ${c.applications.join('; ')}.`);
  if (c.specs?.length) L.push(`Specifications: ${c.specs.map((s) => `${s.label}: ${s.value}`).join('; ')}.`);
  if (c.hardware?.length) L.push(`Hardware: ${c.hardware.map((s) => `${s.label}: ${s.value}`).join('; ')}.`);
}
L.push(`
## How the website works
- Home (/): company overview, products, solutions, energy dashboard preview, contact form.
- Store (/store): hardware catalogue. Buying needs an account. Payment is by Paystack (card or M-Pesa) in KES; the licence and
  protected documentation unlock automatically once Paystack confirms the payment. Orders: /portal/orders. Licences: /portal/licenses. Documentation library: /portal/library.
- MOTECH for Engineering Students (/students): marketplace of complete engineering projects for students. Free account, pay with Paystack,
  download from /students/my-projects. Many projects have a demo video (max 3 minutes) on the project page before buying. All content is copyright MOTECH, licensed for personal study only.
- Accounts: /register to create, /login to sign in, "Forgot password" on the login page sends a reset link. Accounts work on any device.
- Admin area (/admin) is only for MOTECH administrators.
- Energy Management Dashboard (${site.dashboardUrl}) is a separate web app for smart-meter monitoring, billing and analytics.
- Refunds, invoices, bulk/utility pricing and custom engineering: contact MOTECH by email or WhatsApp above.
`);

const text = L.join('\n');
writeFileSync('supabase/functions/site-assistant/knowledge.ts',
  `// GENERATED by scripts/build-assistant-knowledge.mjs — do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(text)};\n`);
console.log(`knowledge.ts written: ${text.length} characters`);
